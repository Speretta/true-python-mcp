#!/usr/bin/env bash
# Create a release from the commits since the last tag.
#
# The version bump is derived from the commit messages:
#   default                        -> patch (0.1.0 -> 0.1.1)
#   footer "Bump: minor"           -> minor (0.1.x -> 0.2.0)
#   breaking change ("type!:" in the subject, or a "BREAKING CHANGE:" or
#   "Bump: major" footer)          -> major (asks first while below 1.0)
#
# Steps: bump the version in Cargo.toml and Cargo.lock, put a new section
# at the top of CHANGELOG.md, commit as "chore(release): vX.Y.Z" and add
# an annotated tag.
#
# Usage: scripts/release.sh [--dry-run]
set -euo pipefail
# ASCII regex semantics regardless of the user's locale (some locales, e.g.
# tr_TR, exclude 'i' from [a-z] in glibc regex ranges).
export LC_ALL=C
cd "$(dirname "$0")/.."

dry_run=false
if [ "${1:-}" = "--dry-run" ]; then
    dry_run=true
fi

current="$(sed -n 's/^version = "\(.*\)"$/\1/p' Cargo.toml | head -n1)"
last_tag="$(git describe --tags --abbrev=0 2>/dev/null || true)"

if [ -n "$last_tag" ]; then
    range="$last_tag..HEAD"
    if [ -z "$(git rev-list "$range")" ]; then
        echo "release: no commits since $last_tag, nothing to do" >&2
        exit 1
    fi
else
    # First release: the version already in Cargo.toml is the release.
    range="HEAD"
fi

subjects="$(git log --format=%s "$range")"
bodies="$(git log --format=%b "$range")"

bump=patch
if grep -qE '^[a-z]+(\([^)]*\))?!: ' <<<"$subjects" ||
    grep -q '^BREAKING CHANGE:' <<<"$bodies" ||
    grep -qE '^Bump: major$' <<<"$bodies"; then
    bump=major
elif grep -qE '^Bump: minor$' <<<"$bodies"; then
    bump=minor
fi

IFS=. read -r major minor patch <<<"$current"
if [ -z "$last_tag" ]; then
    next="$current"
else
    case "$bump" in
        major) next="$((major + 1)).0.0" ;;
        minor) next="$major.$((minor + 1)).0" ;;
        patch) next="$major.$minor.$((patch + 1))" ;;
    esac
fi

echo "release: $current -> v$next ($bump)"
if $dry_run; then
    git log --oneline "$range" | sed 's/^/  /'
    exit 0
fi

if [ "$bump" = major ] && [ "$major" -eq 0 ]; then
    read -r -p "release: breaking change below 1.0 becomes v$next, continue? [y/N] " answer
    if [ "$answer" != y ]; then
        echo "release: aborted" >&2
        exit 1
    fi
fi

# Build the changelog section: group the subjects by commit type.
today="$(date +%Y-%m-%d)"
section="$(mktemp)"
trap 'rm -f "$section"' EXIT
{
    echo "## [$next] - $today"
    echo
    added="$(sed -nE 's/^feat(\([^)]*\))?!?: /- /p' <<<"$subjects" || true)"
    fixed="$(sed -nE 's/^fix(\([^)]*\))?!?: /- /p' <<<"$subjects" || true)"
    other="$(sed -nE 's/^(refactor|perf|docs|test|build|ci|chore)(\([^)]*\))?!?: /- /p' <<<"$subjects" || true)"
    if [ -n "$added" ]; then echo "### Added"; echo; echo "$added"; echo; fi
    if [ -n "$fixed" ]; then echo "### Fixed"; echo; echo "$fixed"; echo; fi
    if [ -n "$other" ]; then echo "### Changed"; echo; echo "$other"; echo; fi
} >"$section"

if [ ! -f CHANGELOG.md ]; then
    {
        echo "# Changelog"
        echo
        echo "Notable changes to this project, newest first."
        echo "Sections are generated by scripts/release.sh from the commit log."
        echo
        cat "$section"
    } >CHANGELOG.md
elif grep -q '^## \[' CHANGELOG.md; then
    awk -v file="$section" '
        BEGIN { while ((getline line < file) > 0) section = section line "\n" }
        !done && /^## \[/ { printf "%s", section; done = 1 }
        { print }
    ' CHANGELOG.md >CHANGELOG.md.new
    mv CHANGELOG.md.new CHANGELOG.md
else
    { echo; cat "$section"; } >>CHANGELOG.md
fi

sed -i "s/^version = \"$current\"$/version = \"$next\"/" Cargo.toml
cargo metadata --format-version 1 >/dev/null # refresh Cargo.lock

git add Cargo.toml Cargo.lock CHANGELOG.md
git commit -m "chore(release): v$next"
git tag -a "v$next" -m "v$next"
echo "release: committed and tagged v$next"
