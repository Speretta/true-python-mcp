#!/usr/bin/env bash
# Create a release from the commits since the last tag.
#
# The version bump is derived from the commit messages:
#   default                        -> patch (0.1.0 -> 0.1.1)
#   footer "Bump: minor"           -> minor (0.1.x -> 0.2.0)
#   breaking change ("type!:" in the subject, or a "BREAKING CHANGE:" or
#   "Bump: major" footer)          -> major (asks first while below 1.0)
#
# Steps: bump the version in Cargo.toml and Cargo.lock, put a new section
# at the top of CHANGELOG.md, commit as "chore(release): vX.Y.Z" and add
# an annotated tag.
#
# Message parsing uses only bash builtins (case patterns and parameter
# expansion) - no regex tools, no character ranges - so it is fast and no
# locale can change what it detects.
#
# Usage: scripts/release.sh [--dry-run]
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")/.."

dry_run=false
if [ "${1:-}" = "--dry-run" ]; then
    dry_run=true
fi

# Current version: the first exact `version = "x.y.z"` line of Cargo.toml.
current=""
while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
        'version = "'*'"')
            current="${line#version = \"}"
            current="${current%\"}"
            break
            ;;
    esac
done <Cargo.toml
if [ -z "$current" ]; then
    echo "release: cannot find a version line in Cargo.toml" >&2
    exit 1
fi

last_tag="$(git describe --tags --abbrev=0 2>/dev/null || true)"
if [ -n "$last_tag" ]; then
    range="$last_tag..HEAD"
    if [ -z "$(git rev-list "$range")" ]; then
        echo "release: no commits since $last_tag, nothing to do" >&2
        exit 1
    fi
else
    # First release: the version already in Cargo.toml is the release.
    range="HEAD"
fi

# Walk the subjects: split each into type and description, group them for
# the changelog, and treat a "!" before ": " as a breaking change.
bump=patch
added=()
fixed=()
other=()
while IFS= read -r subject || [ -n "$subject" ]; do
    if [ -z "$subject" ]; then
        continue
    fi
    case "$subject" in
        *": "*) ;;
        *)
            other+=("- $subject")
            continue
            ;;
    esac
    prefix="${subject%%: *}"
    rest="${subject#*: }"
    case "$prefix" in
        *!)
            bump=major
            prefix="${prefix%!}"
            ;;
    esac
    case "$prefix" in
        *"("*")") prefix="${prefix%%(*}" ;;
    esac
    case "$prefix" in
        feat) added+=("- $rest") ;;
        fix) fixed+=("- $rest") ;;
        refactor | perf | docs | test | build | ci | chore) other+=("- $rest") ;;
        *) other+=("- $subject") ;;
    esac
done <<<"$(git log --format=%s "$range")"

# Walk the message bodies for the bump footers.
while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
        "BREAKING CHANGE:"* | "Bump: major") bump=major ;;
        "Bump: minor")
            if [ "$bump" = patch ]; then
                bump=minor
            fi
            ;;
    esac
done <<<"$(git log --format=%b "$range")"

IFS=. read -r major minor patch <<<"$current"
if [ -z "$last_tag" ]; then
    next="$current"
else
    case "$bump" in
        major) next="$((major + 1)).0.0" ;;
        minor) next="$major.$((minor + 1)).0" ;;
        patch) next="$major.$minor.$((patch + 1))" ;;
    esac
fi

echo "release: $current -> v$next ($bump)"
if $dry_run; then
    while IFS= read -r line || [ -n "$line" ]; do
        echo "  $line"
    done <<<"$(git log --oneline "$range")"
    exit 0
fi

if [ "$bump" = major ] && [ "$major" -eq 0 ]; then
    read -r -p "release: breaking change below 1.0 becomes v$next, continue? [y/N] " answer
    if [ "$answer" != y ]; then
        echo "release: aborted" >&2
        exit 1
    fi
fi

# Build the changelog section: subjects grouped by commit type.
today="$(date +%Y-%m-%d)"
section=("## [$next] - $today" "")
if [ "${#added[@]}" -gt 0 ]; then
    section+=("### Added" "" "${added[@]}" "")
fi
if [ "${#fixed[@]}" -gt 0 ]; then
    section+=("### Fixed" "" "${fixed[@]}" "")
fi
if [ "${#other[@]}" -gt 0 ]; then
    section+=("### Changed" "" "${other[@]}" "")
fi

if [ ! -f CHANGELOG.md ]; then
    {
        echo "# Changelog"
        echo
        echo "Notable changes to this project, newest first."
        echo "Sections are generated by scripts/release.sh from the commit log."
        echo
        printf '%s\n' "${section[@]}"
    } >CHANGELOG.md
else
    # Insert the section above the first "## [" heading.
    out=()
    inserted=false
    while IFS= read -r line || [ -n "$line" ]; do
        if ! $inserted; then
            case "$line" in
                "## ["*)
                    out+=("${section[@]}")
                    inserted=true
                    ;;
            esac
        fi
        out+=("$line")
    done <CHANGELOG.md
    if ! $inserted; then
        out+=("" "${section[@]}")
    fi
    printf '%s\n' "${out[@]}" >CHANGELOG.md
fi

# Swap the exact version line in Cargo.toml (no pattern matching).
version_old="version = \"$current\""
version_new="version = \"$next\""
out=()
replaced=false
while IFS= read -r line || [ -n "$line" ]; do
    if ! $replaced && [ "$line" = "$version_old" ]; then
        line="$version_new"
        replaced=true
    fi
    out+=("$line")
done <Cargo.toml
if ! $replaced; then
    echo "release: version line vanished from Cargo.toml while editing" >&2
    exit 1
fi
printf '%s\n' "${out[@]}" >Cargo.toml

cargo metadata --format-version 1 >/dev/null # refresh Cargo.lock

git add Cargo.toml Cargo.lock CHANGELOG.md
git commit -m "chore(release): v$next"
git tag -a "v$next" -m "v$next"
echo "release: committed and tagged v$next"
